// Regenerates src/domains.js from the CC0 disposable-email-domains project
// and src/relays.js from the privacy relays the plugin always lets through.
//   node scripts/update-domains.mjs

import { writeFile } from 'node:fs/promises';

const SOURCE =
  'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';

const res = await fetch(SOURCE, { signal: AbortSignal.timeout(60000) });
if (!res.ok) throw new Error(`blocklist: HTTP ${res.status}`);
const domains = [
  ...new Set(
    (await res.text())
      .split('\n')
      .map((l) => l.trim().toLowerCase())
      .filter((l) => l && !l.startsWith('#') && /^[a-z0-9.-]+\.[a-z0-9-]{2,}$/.test(l)),
  ),
].sort();
if (domains.length < 1000) throw new Error(`suspiciously short list (${domains.length})`);

await writeFile(
  new URL('../src/domains.js', import.meta.url),
  `// ${domains.length} disposable email domains, ${new Date().toISOString().slice(0, 10)}.
// Source: github.com/disposable-email-domains/disposable-email-domains (CC0 1.0).
// Generated by scripts/update-domains.mjs - do not edit by hand.
export const DISPOSABLE = new Set(${JSON.stringify(domains.join('\n'))}.split('\\n'));
`,
);
console.log(`wrote ${domains.length} domains`);
